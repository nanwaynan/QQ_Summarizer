# ---------- 图片评分 ----------

SCORE_PROMPT = """你在帮用户整理 QQ 群「{group_name}」的聊天记录。
下面是一批聊天中出现的图片，请判断**哪些值得保留在总结报告里**，供用户快速理解当天发生了什么。

评分标准（1-5 分）：
- **5 分**：核心信息载体。如：重要报错/日志截图、教程步骤、配置代码、数据图表、资源链接截图、关键公告
- **4 分**：有参考价值。如：软件界面、工具截图、成果展示、有信息量的对话截图
- **3 分**：弱相关。如：日常闲聊配图、与话题关联不大但可看的图
- **2 分**：低价值。如：随手发的模糊照片、无关表情、重复内容
- **1 分**：应丢弃。如：纯装饰图、无意义截图、广告图、与讨论无关

考虑因素：
- 图片本身的内容是否有信息量
- 是否与上下文讨论的技术话题相关
- 是否重复（同类图只留最有代表性的）

输出格式（每张一行，不要其他内容）：
1|评分|简短理由(15字内)
2|评分|简短理由(15字内)
..."""


